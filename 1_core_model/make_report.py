"""
make_report.py
==============
Generate the results section of RESEARCH_NOTES from the cached experiment
CSVs, so every number in the write-up is read straight from the data rather
than transcribed by hand.

Usage:  python3 make_report.py > results/RESULTS_SECTION.md
"""



from __future__ import annotations

import sys as _sys, os as _os
for _p in (_os.getcwd(), _os.path.dirname(_os.path.abspath(__file__))):
    _r=_os.path.dirname(_p)
    if _os.path.exists(_os.path.join(_r,"batman_atomic.py")) and _r not in _sys.path:
        _sys.path.insert(0,_r)
# --- end bootstrap: shared library lives one level up ---

import os

import numpy as np
import pandas as pd

import batman_atomic as ba
import experiments as ex

R = ex.RESULTS_DIR
ORDER = ["fixed", "learned", "atomic"]
NAME = {"fixed": "Fixed BLOSUM100", "learned": "Learned 20x20 (BATMAN)",
        "atomic": "Atomic (proposed)"}


def _have(fname: str) -> bool:
    return os.path.exists(os.path.join(R, fname))


def _load(fname: str) -> pd.DataFrame:
    return pd.read_csv(os.path.join(R, fname))


def fmt_p(p: float) -> str:
    if p is None or (isinstance(p, float) and np.isnan(p)):
        return "n/a"
    if p < 1e-4:
        return "&lt;0.0001"
    return f"{p:.4f}"


def summary_table(long_df: pd.DataFrame, title: str) -> str:
    s = ex.summarize(long_df).set_index("model")
    lines = [f"**{title}**", "",
             "| model | mean per-TCR AUC | bootstrap 95% CI | n TCRs |",
             "|---|---|---|---|"]
    best = max((s.loc[m, "mean_auc"] for m in ORDER if m in s.index), default=np.nan)
    for m in ORDER:
        if m not in s.index:
            continue
        row = s.loc[m]
        val = f"{row.mean_auc:.4f}"
        if np.isclose(row.mean_auc, best):
            val = f"**{val}**"
        lines.append(f"| {NAME[m]} | {val} | "
                     f"[{row.ci_low:.4f}, {row.ci_high:.4f}] | {int(row.n_tcr)} |")
    return "\n".join(lines)


def paired_table(long_df: pd.DataFrame, pairs) -> str:
    lines = ["| comparison | n TCRs | median AUC difference | Wilcoxon p | significant |",
             "|---|---|---|---|---|"]
    for a, b in pairs:
        t = ex.compare_models(long_df, a, b)
        p = t.get("p", float("nan"))
        sig = "yes" if (isinstance(p, float) and not np.isnan(p) and p < 0.05) else "no"
        lines.append(f"| {NAME[a]} vs {NAME[b]} | {t['n']} | "
                     f"{t['median_diff']:+.4f} | {fmt_p(p)} | {sig} |")
    return "\n".join(lines)


def main() -> None:
    out: list[str] = []
    add = out.append

    add("<!-- generated by make_report.py -- do not edit by hand -->")
    add("")

    # ---------------- Experiment 1 ----------------
    if _have("exp1_cross_validation.csv"):
        cv = _load("exp1_cross_validation.csv")
        add("### การทดลองที่ 1 — In-distribution 5-fold CV (ครบทุก TCR)")
        add("")
        lengths = ", ".join(str(int(x)) for x in sorted(cv.L.unique()))
        add(summary_table(cv, f"{cv.tcr.nunique()} TCRs, "
                              f"index-peptide lengths {lengths}"))
        add("")
        add(paired_table(cv, [("atomic", "fixed"), ("atomic", "learned"),
                              ("learned", "fixed")]))
        add("")

    # ---------------- Experiment 2 ----------------
    if _have("exp2_leave_chemistry_out.csv"):
        chem = _load("exp2_leave_chemistry_out.csv")
        add("### การทดลองที่ 2 — Leave-chemistry-out")
        add("")
        tab = (ex.summarize(chem, within=["group"])
               .pivot(index="group", columns="model", values="mean_auc")[ORDER])
        lines = ["| held-out group | " + " | ".join(NAME[m] for m in ORDER) + " | winner |",
                 "|---|---|---|---|---|"]
        for g, row in tab.iterrows():
            win = row.idxmax()
            cells = " | ".join(
                (f"**{row[m]:.4f}**" if m == win else f"{row[m]:.4f}") for m in ORDER)
            lines.append(f"| {g} | {cells} | {NAME[win]} |")
        mean_row = tab.mean()
        win = mean_row.idxmax()
        cells = " | ".join(
            (f"**{mean_row[m]:.4f}**" if m == win else f"{mean_row[m]:.4f}") for m in ORDER)
        lines.append(f"| **เฉลี่ย** | {cells} | {NAME[win]} |")
        add("\n".join(lines))
        add("")
        wins = sum(1 for _, row in tab.iterrows() if row.idxmax() == "atomic")
        add(f"atomic ชนะ **{wins} จาก {len(tab)} กลุ่ม**")
        add("")
        add("ผล paired test แยกรายกลุ่ม:")
        add("")
        lines = ["| group | atomic vs fixed (p) | atomic vs learned (p) |", "|---|---|---|"]
        for g in tab.index:
            sub = chem[chem.group == g]
            p1 = ex.compare_models(sub, "atomic", "fixed").get("p", float("nan"))
            p2 = ex.compare_models(sub, "atomic", "learned").get("p", float("nan"))
            lines.append(f"| {g} | {fmt_p(p1)} | {fmt_p(p2)} |")
        add("\n".join(lines))
        add("")
        add("**ผลรวมทุกกลุ่ม (pooled, จับคู่ราย TCR)** -- "
            "เป็นตัวเลขที่ควรอ้างอิงเพราะมีกำลังทางสถิติสูงสุด:")
        add("")
        add(paired_table(chem, [("atomic", "fixed"), ("atomic", "learned"),
                                ("learned", "fixed")]))
        add("")

    # ---------------- Experiment 3 ----------------
    if _have("exp3_feature_ablation.csv") and _have("exp2_leave_chemistry_out.csv"):
        abl = _load("exp3_feature_ablation.csv")
        chem = _load("exp2_leave_chemistry_out.csv")
        base = chem[chem.model == "atomic"].assign(features="base8")
        allf = pd.concat([base, abl], ignore_index=True)
        piv = (allf.groupby(["features", "group", "tcr"], as_index=False).auc.mean()
               .groupby(["features", "group"], as_index=False).auc.mean()
               .pivot(index="group", columns="features", values="auc"))
        cols = [c for c in ["base8", "plus_logp", "full11"] if c in piv.columns]
        piv = piv[cols]
        mat = (chem[chem.model != "atomic"]
               .groupby(["group", "model", "tcr"], as_index=False).auc.mean()
               .groupby(["group", "model"], as_index=False).auc.mean()
               .groupby("group").auc.max())
        piv["best matrix baseline"] = mat

        add("### การทดลองที่ 3 — Feature ablation (atomic เท่านั้น)")
        add("")
        header = "| held-out group | " + " | ".join(cols) + " | best matrix baseline |"
        add(header)
        add("|---" * (len(cols) + 2) + "|")
        for g, row in piv.iterrows():
            add(f"| {g} | " + " | ".join(f"{row[c]:.4f}" for c in cols)
                + f" | {row['best matrix baseline']:.4f} |")
        m = piv.mean()
        add("| **เฉลี่ย** | " + " | ".join(f"**{m[c]:.4f}**" for c in cols)
            + f" | {m['best matrix baseline']:.4f} |")
        add("")

    # ---------------- Experiment 4 ----------------
    if _have("exp4_novel_tcr.csv"):
        novel = _load("exp4_novel_tcr.csv")
        add("### การทดลองที่ 4 — Novel-TCR generalization (pan-TCR weights)")
        add("")
        add(summary_table(novel, f"{novel.tcr.nunique()} held-out TCRs"))
        add("")
        add(paired_table(novel, [("atomic", "fixed"), ("atomic", "learned")]))
        add("")

    # ---------------- Experiment 5 ----------------
    if _have("exp5_multi_mutant.csv"):
        mm = _load("exp5_multi_mutant.csv")
        per = mm[mm.tcr != "__overall__"]
        add("### การทดลองที่ 5 — Multi-aa mutants (train single-aa → test multi-aa)")
        add("")
        add(summary_table(per, f"{per.tcr.nunique()} TCRs, Hamming distance 2-9"))
        add("")
        add(paired_table(per, [("atomic", "fixed"), ("atomic", "learned")]))
        add("")
        det = per.pivot_table(index="tcr", columns="model", values="auc")[ORDER]
        add("ผลรายตัว TCR (กระจายกว้างมาก):")
        add("")
        add("| TCR | " + " | ".join(NAME[m] for m in ORDER) + " |")
        add("|---|---|---|---|")
        for t, row in det.iterrows():
            add(f"| {t} | " + " | ".join(f"{row[m]:.3f}" for m in ORDER) + " |")
        add("")

    # ---------------- Experiment 6 ----------------
    if _have("exp6_nuts_vs_advi.csv"):
        nuts = _load("exp6_nuts_vs_advi.csv")
        piv = nuts.pivot_table(index="feature_idx", columns="method",
                               values=["theta_mean", "theta_sd"])
        feats = list(ba.build_atomic_features("base8").columns)
        piv.index = feats[:len(piv)]
        n_rows = nuts[nuts.method == "nuts"]
        corr = np.corrcoef(piv[("theta_mean", "advi")], piv[("theta_mean", "nuts")])[0, 1]
        ratio = (piv[("theta_sd", "advi")] / piv[("theta_sd", "nuts")]).mean()
        auc = nuts.groupby("method").auc.first()

        add("### การทดลองที่ 6 — NUTS (full MCMC) vs ADVI (variational)")
        add("")
        add(f"- **NUTS convergence:** max r-hat **{n_rows.rhat.max():.4f}** "
            f"(เกณฑ์ < 1.01) · min ESS **{n_rows.ess.min():.0f}** (เกณฑ์ > 400) → ผ่าน")
        add(f"- **Test AUC:** ADVI {auc['advi']:.4f} · NUTS {auc['nuts']:.4f}")
        add(f"- **ความสอดคล้องของ posterior mean:** r = **{corr:.4f}**")
        add(f"- **อัตราส่วน posterior SD (ADVI/NUTS):** **{ratio:.2f}** "
            f"→ ADVI ประเมิน uncertainty แคบกว่าจริง ~{(1 - ratio) * 100:.0f}%")
        add("")
        add("| feature | theta ADVI | theta NUTS | SD ADVI | SD NUTS |")
        add("|---|---|---|---|---|")
        for f in piv.index:
            add(f"| {f} | {piv.loc[f, ('theta_mean', 'advi')]:.3f} | "
                f"{piv.loc[f, ('theta_mean', 'nuts')]:.3f} | "
                f"{piv.loc[f, ('theta_sd', 'advi')]:.3f} | "
                f"{piv.loc[f, ('theta_sd', 'nuts')]:.3f} |")
        add("")

    # ---------------- Experiment 7 ----------------
    if _have("exp7_pmhc_term.csv"):
        pmr = _load("exp7_pmhc_term.csv")
        s = ex.summarize(pmr, by="pmhc").set_index("pmhc")
        add("### การทดลองที่ 7 — pMHC binding term")
        add("")
        add("| variant | mean per-TCR AUC | bootstrap 95% CI | n TCRs |")
        add("|---|---|---|---|")
        for k in s.index:
            add(f"| {k} | {s.loc[k, 'mean_auc']:.4f} | "
                f"[{s.loc[k, 'ci_low']:.4f}, {s.loc[k, 'ci_high']:.4f}] | "
                f"{int(s.loc[k, 'n_tcr'])} |")
        per = pmr.groupby(["pmhc", "tcr"], as_index=False).auc.mean()
        a = dict(zip(per[per.pmhc == "with pMHC"].tcr, per[per.pmhc == "with pMHC"].auc))
        b = dict(zip(per[per.pmhc == "no pMHC"].tcr, per[per.pmhc == "no pMHC"].auc))
        t = ba.paired_wilcoxon(a, b)
        add("")
        add(f"paired Wilcoxon (with vs without): n = {t['n']}, "
            f"median difference {t['median_diff']:+.4f}, p = {fmt_p(t.get('p'))}")
        add("")

    print("\n".join(out))


if __name__ == "__main__":
    main()
