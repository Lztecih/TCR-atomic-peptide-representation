"""
manuscript_tables.py
====================
Builds every numbered table in the manuscript straight from ``results/``, so
no figure in the paper can drift from the data behind it.

The multiple-comparison correction is applied ONCE, over the whole family of
pre-specified tests reported in the paper, rather than per table -- that was
review item R1, and doing it per table would quietly reintroduce the problem.

Usage:  python3 manuscript_tables.py > TABLES.md
"""

