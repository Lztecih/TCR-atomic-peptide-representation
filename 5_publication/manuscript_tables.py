import os
import warnings

warnings.filterwarnings("ignore")

import numpy as np
import pandas as pd
from scipy import stats

import batman_atomic as ba

RES = os.path.join(ba.ROOT, "results")

NAME = {
    "fixed": "Fixed BLOSUM100", "atchley5": "Atchley-5 (2005)",
    "atomic": "Atomic (8 param.)", "learned": "Learned 20×20 (BATMAN)",
    "hybrid_frozen": "Frozen hybrid (this work)", "hamming": "Hamming",
    "blosum_uniform": "BLOSUM100, uniform weights",
}
ORDER = ["fixed", "atchley5", "atomic", "learned", "hybrid_frozen"]


def L(name):
    return pd.read_csv(os.path.join(RES, name))


def have(name):
    return os.path.exists(os.path.join(RES, name))


def per_unit(df, model, keys):
    return df[df.model == model].groupby(keys).auc.mean()


def boot_ci(v, n=10000, seed=0):
    rng = np.random.default_rng(seed)
    v = np.asarray(v, float)
    return np.percentile(rng.choice(v, size=(n, len(v)), replace=True).mean(1),
                         [2.5, 97.5])


def paired(df, m1, m2, keys):
    a, b = per_unit(df, m1, keys), per_unit(df, m2, keys)
    j = pd.concat([a, b], axis=1, join="inner", keys=["a", "b"]).dropna()
    d = j.a - j.b
    return dict(n=len(j), mean=float(d.mean()), median=float(d.median()),
                win=float((d > 0).mean()),
                d=float(d.mean() / d.std(ddof=1)),
                p=float(stats.wilcoxon(j.a, j.b).pvalue))


def fmt_p(p):
    return "&lt;1e-20" if p < 1e-20 else (f"{p:.1e}" if p < 1e-4 else f"{p:.4f}")


def bh_fdr(ps):
    """Benjamini-Hochberg adjusted p-values."""
    ps = np.asarray(ps, float)
    n = len(ps)
    order = np.argsort(ps)
    adj = np.empty(n)
    prev = 1.0
    for rank, i in enumerate(order[::-1]):
        k = n - rank
        prev = min(prev, ps[i] * n / k)
        adj[i] = prev
    return adj


# --------------------------------------------------------------------------
def source_tables():
    """(label, in-distribution df, OOD df, keys) for the benchmark."""
    if have("exp8_harmonized_protocol.csv"):
        h = L("exp8_harmonized_protocol.csv")
        ind = h[h.setting == "in_distribution"].copy()
        ood = h[h.setting == "leave_chemistry_out"].copy()
        label = ("harmonised protocol: single-aa mutant rows only "
                 "(`mutation_position > 0`) for training and testing in both "
                 "settings")
    else:
        # Fallback: stitch the original runs together. The hybrid's stage 2
        # sits on top of the stage-1 atomic fit from ITS OWN run, so the
        # atomic rows must come from that same run -- averaging in exp1's
        # separate atomic fit would blend two runs into one "atomic" column
        # and distort every comparison involving it.
        hy = L("hybrid_frozen_s025.csv")
        e1 = L("exp1_cross_validation.csv")
        e2 = L("exp2_leave_chemistry_out.csv")
        ind = pd.concat([e1[e1.model != "atomic"],
                         hy[hy.setting == "in_distribution"]],
                        ignore_index=True)
        ood = pd.concat([e2[e2.model != "atomic"],
                         hy[hy.setting == "leave_chemistry_out"]],
                        ignore_index=True)
        label = ("original protocol (Exp1 retains index-peptide rows in "
                 "training; Exp2 does not)")
    at_cv = L("review_atchley_cv.csv").rename(columns={"encoding": "model"})
    at_ch = L("review_atchley_chem.csv").rename(columns={"encoding": "model"})
    ind = pd.concat([ind, at_cv], ignore_index=True)
    ood = pd.concat([ood, at_ch], ignore_index=True)
    return label, ind, ood


def main():
    label, ind, ood = source_tables()
    print("# Manuscript tables\n")
    print("*Generated by `manuscript_tables.py` from `results/`. "
          "Do not edit by hand.*\n")
    print(f"Benchmark source: {label}.\n")

    # ================================================== Table 1 ============
    print("## Table 1 — Predictive accuracy across 151 TCRs\n")
    print("Unit of analysis is one TCR (in-distribution) or one "
          "TCR × chemistry-group (OOD); 95% CI by percentile bootstrap "
          "(10,000 resamples).\n")
    print("| Representation | free param. in *M* | in-distribution AUC "
          "[95% CI] | out-of-distribution AUC [95% CI] |")
    print("|---|---|---|---|")
    NP = {"fixed": "0", "atchley5": "5", "atomic": "8",
          "learned": "~380", "hybrid_frozen": "8 frozen + 400 shrunk"}
    for m in ORDER:
        if m not in set(ind.model):
            continue
        vi = per_unit(ind, m, ["tcr"]).to_numpy()
        ci = boot_ci(vi)
        cell_i = f"{vi.mean():.4f} [{ci[0]:.4f}, {ci[1]:.4f}]"
        if m in set(ood.model):
            vo = per_unit(ood, m, ["tcr", "group"]).to_numpy()
            co = boot_ci(vo)
            cell_o = f"{vo.mean():.4f} [{co[0]:.4f}, {co[1]:.4f}]"
        else:
            cell_o = "—"
        print(f"| {NAME[m]} | {NP[m]} | {cell_i} | {cell_o} |")

    # ================================================== Table 2 ============
    # every pre-specified test, corrected together (review item R1)
    tests = [
        ("atomic vs fixed", ind, "atomic", "fixed", ["tcr"], "in-dist"),
        ("atomic vs Atchley-5", ind, "atomic", "atchley5", ["tcr"], "in-dist"),
        ("learned vs atomic", ind, "learned", "atomic", ["tcr"], "in-dist"),
        ("learned vs fixed", ind, "learned", "fixed", ["tcr"], "in-dist"),
        ("hybrid vs atomic", ind, "hybrid_frozen", "atomic", ["tcr"], "in-dist"),
        ("hybrid vs learned", ind, "hybrid_frozen", "learned", ["tcr"], "in-dist"),
        ("atomic vs fixed", ood, "atomic", "fixed", ["tcr", "group"], "OOD"),
        ("atomic vs Atchley-5", ood, "atomic", "atchley5", ["tcr", "group"], "OOD"),
        ("atomic vs learned", ood, "atomic", "learned", ["tcr", "group"], "OOD"),
        ("hybrid vs atomic", ood, "hybrid_frozen", "atomic", ["tcr", "group"], "OOD"),
        ("hybrid vs learned", ood, "hybrid_frozen", "learned", ["tcr", "group"], "OOD"),
    ]
    rows = []
    for lab, df, m1, m2, keys, tag in tests:
        if m1 not in set(df.model) or m2 not in set(df.model):
            continue
        r = paired(df, m1, m2, keys)
        rows.append(dict(test=lab, setting=tag, **r))

    # the pMHC negative result belongs to the same family
    e7 = L("exp7_pmhc_term.csv")
    a = e7[e7.pmhc == "with pMHC"].groupby("tcr").auc.mean()
    b = e7[e7.pmhc == "no pMHC"].groupby("tcr").auc.mean()
    j = pd.concat([a, b], axis=1, join="inner", keys=["a", "b"]).dropna()
    dd = j.a - j.b
    rows.append(dict(test="pMHC term vs none", setting="in-dist", n=len(j),
                     mean=float(dd.mean()), median=float(dd.median()),
                     win=float((dd > 0).mean()),
                     d=float(dd.mean() / dd.std(ddof=1)),
                     p=float(stats.wilcoxon(j.a, j.b).pvalue)))

    t2 = pd.DataFrame(rows)
    t2["p_bh"] = bh_fdr(t2.p.values)
    t2["p_bonf"] = np.minimum(t2.p.values * len(t2), 1.0)

    print(f"\n## Table 2 — Paired comparisons, corrected over all "
          f"{len(t2)} pre-specified tests\n")
    print("Paired Wilcoxon signed-rank on the per-TCR AUCs. Correction is "
          "applied across the **whole family** of tests below, not per table.\n")
    print("| Comparison | Setting | *n* | ΔAUC | win rate | Cohen's *d* | "
          "raw *p* | BH-FDR | Bonferroni |")
    print("|---|---|---|---|---|---|---|---|---|")
    for r in t2.itertuples():
        bh = "✅" if r.p_bh < .05 else "❌"
        bf = "✅" if r.p_bonf < .05 else "❌"
        print(f"| {r.test} | {r.setting} | {r.n} | {r.mean:+.4f} | "
              f"{r.win*100:.1f}% | {r.d:+.2f} | {fmt_p(r.p)} | "
              f"{bh} {r.p_bh:.3f} | {bf} {r.p_bonf:.3f} |")

    # ================================================== Table 3 ============
    print("\n## Table 3 — Learning-free baselines\n")
    print("Establishes how much of the accuracy comes from the fitted "
          "substitution model at all.\n")
    print("| Scoring rule | learns anything? | mean per-TCR AUC |")
    print("|---|---|---|")
    print("| Hamming distance, uniform weights | no | 0.5095 |")
    print("| BLOSUM100, uniform weights | no | 0.5591 |")
    print("| Mutated position only | no | 0.5765 |")
    best = max(per_unit(ind, m, ["tcr"]).mean() for m in ORDER
               if m in set(ind.model))
    worst = min(per_unit(ind, m, ["tcr"]).mean() for m in ORDER
                if m in set(ind.model))
    print(f"| **Any fitted model in Table 1** | yes | "
          f"**{worst:.4f} – {best:.4f}** |")
    print("\nValues for the three unfitted rules are from "
          "`2_adversarial_review/review_checks.py`.\n")

    # ================================================== Table 4 ============
    sw = L("review_hybrid_shrinkage.csv")
    si = sw[sw.setting == "in_distribution"].groupby("shrinkage").auc.mean()
    so = sw[sw.setting == "leave_chemistry_out"].groupby("shrinkage").auc.mean()
    hy = L("hybrid_frozen_s025.csv")
    at_o = hy[(hy.setting == "leave_chemistry_out") & (hy.model == "atomic")] \
        .groupby(["tcr", "group"]).auc.mean().mean()
    fz_i = hy[(hy.setting == "in_distribution") &
              (hy.model == "hybrid_frozen")].groupby("tcr").auc.mean().mean()
    fz_o = hy[(hy.setting == "leave_chemistry_out") &
              (hy.model == "hybrid_frozen")] \
        .groupby(["tcr", "group"]).auc.mean().mean()

    print("## Table 4 — Why the backbone must be frozen\n")
    print("A *jointly* fitted residual buys in-distribution accuracy by "
          "spending OOD accuracy, at every shrinkage σ tried. Freezing the "
          "backbone does not.\n")
    print("| Hybrid variant | σ | in-distribution | OOD | OOD vs atomic-only |")
    print("|---|---|---|---|---|")
    for s in si.index:
        print(f"| joint (θ and residual fitted together) | {s:g} | "
              f"{si.loc[s]:.4f} | {so.loc[s]:.4f} | {so.loc[s]-at_o:+.4f} |")
    print(f"| **frozen backbone (this work)** | 0.25 | **{fz_i:.4f}** | "
          f"**{fz_o:.4f}** | **{fz_o-at_o:+.4f}** |")
    rho_i = stats.spearmanr(si.index, si.values).statistic
    rho_o = stats.spearmanr(so.index, so.values).statistic
    print(f"\nFor the joint variant, Spearman ρ(σ, in-distribution) = "
          f"{rho_i:+.2f} and ρ(σ, OOD) = {rho_o:+.2f}: the trade-off is "
          f"monotone, so no choice of σ escapes it.\n")

    # ================================================== Table 5 ============
    if have("proteome_null_baselines.csv"):
        nb = L("proteome_null_baselines.csv")
        nb = nb[nb.threshold_name == "text"]
        print("## Table 5 — Proteome-scale target retrieval\n")
        print("Median rank of an experimentally validated target. Hit "
              "thresholds are per screen because the screens differ in "
              "dynamic range.\n")
        cols = ["hamming", "blosum_uniform", "fixed", "learned", "atomic",
                "hybrid_frozen"]
        hdr = " | ".join(NAME[c] for c in cols)
        print(f"| Screen | peptides | hits | {hdr} |")
        print("|---" * (3 + len(cols)) + "|")
        for s in ["ctag1b_genome", "hiv_genome", "hiv_virome"]:
            sub = nb[nb.screen == s]
            if not len(sub):
                continue
            n_sc = int(sub.n_scored.iloc[0]); n_h = int(sub.n_hits.iloc[0])
            vals = " | ".join(
                f"{float(sub[sub.model == c].median_hit_rank.iloc[0]):.1f}"
                for c in cols)
            print(f"| {s.replace('_', ' ')} | {n_sc:,} | {n_h} | {vals} |")
        print("\nNo fitted model improves on the learning-free Hamming "
              "baseline on any screen.\n")

    # ================================================== Table 6 ============
    if have("noncanonical_distances.csv"):
        nc = L("noncanonical_distances.csv")
        print("## Table 6 — Scoring residues the model has never seen\n")
        print("A 20×20 matrix has no entry for any of these; the atomic model "
              "scores them from structure alone, with no retraining. "
              "**These are capability demonstrations, not accuracy "
              "validations** — no mutational-scan dataset contains modified "
              "residues.\n")
        print("| Modified residue | parent | *M*(parent, modified) | "
              "percentile of canonical substitutions (%) | nearest canonical | "
              "2nd nearest |")
        print("|---|---|---|---|---|---|")
        for r in nc.itertuples():
            print(f"| {r.residue} | {r.parent} | {r.d_to_parent:.2f} | "
                  f"{r.parent_percentile:.0f} | {r.nearest} | {r.second} |")
        cit = nc[nc.residue.str.startswith("Cit")].iloc[0]
        print(f"\nPre-registered falsification check: citrulline's nearest "
              f"canonical residue was predicted to be Q. Observed: "
              f"**{cit.nearest}** — the check **fails as stated**. Citrulline "
              f"is isosteric with arginine, so the entire *M*(R, Cit) distance "
              f"is the charge term; Q is the nearest *non-parent* residue. "
              f"See `results/noncanonical_citrulline_decomp.csv`.\n")

    # ================================================== Table 7 ============
    e6 = L("exp6_nuts_vs_advi.csv")
    nuts = e6[e6.method == "nuts"].sort_values("feature_idx")
    advi = e6[e6.method == "advi"].sort_values("feature_idx")
    ratio = advi.theta_sd.to_numpy() / nuts.theta_sd.to_numpy()
    print("## Table 7 — Variational inference check (ADVI vs NUTS)\n")
    print(f"NUTS converged (max R̂ = {nuts.rhat.max():.4f}, min ESS = "
          f"{nuts.ess.min():.0f}). Posterior *means* agree closely "
          f"(r = {np.corrcoef(advi.theta_mean, nuts.theta_mean)[0,1]:.3f}) "
          f"and test AUC differs by "
          f"{abs(advi.auc.iloc[0]-nuts.auc.iloc[0]):.4f}.\n")
    print("| Feature | θ (ADVI) | θ (NUTS) | SD (ADVI) | SD (NUTS) | SD ratio |")
    print("|---|---|---|---|---|---|")
    for k, name in enumerate(ba.FEATURE_SETS["base8"]):
        print(f"| {name} | {advi.theta_mean.iloc[k]:.3f} | "
              f"{nuts.theta_mean.iloc[k]:.3f} | {advi.theta_sd.iloc[k]:.3f} | "
              f"{nuts.theta_sd.iloc[k]:.3f} | {ratio[k]:.2f} |")
    print(f"\nMedian SD ratio {np.median(ratio):.2f}: ADVI understates "
          f"posterior width by ~{(1-np.median(ratio))*100:.0f}%. Point "
          f"estimates are therefore reported; ADVI credible intervals are "
          f"**not** treated as calibrated.\n")


if __name__ == "__main__":
    main()
